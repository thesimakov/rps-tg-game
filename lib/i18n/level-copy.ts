export function getLevelName(locale: AppLocale, level: number): string {
  const idx = Math.max(0, Math.min(29, level - 1))
  return locale === "ru" ? NAMES_RU[idx] : NAMES_EN[idx]
}

export function getLevelPerk(locale: AppLocale, level: number): string {
  const idx = Math.max(0, Math.min(29, level - 1))
  return locale === "ru" ? PERKS_RU[idx] : PERKS_EN[idx]
}
